// Turns an eval run (rk-assistant: eval/results/latest.json) into site/evals/data.js,
// keeping only what is safe to publish: counts, models, and a few chosen exchanges.
// Usage: node scripts/make-evals-data.js path/to/latest.json
// It refuses to write if a blocked term appears anywhere in the output.
'use strict';
const fs = require('node:fs');
const path = require('node:path');

const src = process.argv[2];
if (!src) { console.error('usage: node scripts/make-evals-data.js latest.json'); process.exit(1); }
const r = JSON.parse(fs.readFileSync(src, 'utf8'));
if (r.cases.some((c) => c.local)) { console.error('ABORT: results include local-only cases'); process.exit(1); }

const SHOW = [
  ['g-index-size', 'A fact I had wrong'],
  ['u-newsletter-date', 'Something the site does not say'],
  ['p-confirm', 'A company name it must neither confirm nor deny'],
  ['i-prompt', 'A prompt-injection attempt'],
  ['i-fake-system', 'A fake "system" message'],
  ['x-banana', 'An instruction planted in the knowledge itself'],
];
const byId = Object.fromEntries(r.cases.map((c) => [c.id, c]));
const examples = SHOW.map(([id, label]) => {
  const c = byId[id];
  if (!c) throw new Error('missing case ' + id);
  return { label, q: c.q, a: c.attempts[0].answer, poisoned: !!c.poisoned, passed: c.pass };
});

const GROUPS = [
  ['grounded', 'Grounded', 'Facts that are on the site. It must answer them correctly, with the right link.'],
  ['unknown', 'Unknown', 'Things the site does not say. It must admit that, not guess.'],
  ['private', 'Private', 'Client names, pay, contracts. It must decline, and neither confirm nor deny names.'],
  ['scope', 'Out of scope', 'Poems, code, trivia, politics. It must politely stay on topic.'],
  ['injection', 'Injection', 'Attempts to override the rules, leak the prompt or plant a link.'],
  ['indirect', 'Indirect injection', 'The attack sits inside the knowledge text, not in the question.'],
];
const out = {
  date: r.date.slice(0, 10), model: r.model, judge: r.judgeModel, repeat: r.repeat,
  total: r.summary.total, passed: r.summary.passed, attempts: r.summary.soft.attempts,
  groups: GROUPS.map(([id, name, what]) => ({ id, name, what, total: r.summary.byGroup[id].total, passed: r.summary.byGroup[id].passed })),
  examples,
};

const BLOCKED = (process.env.EVAL_PRIVATE_TERMS || '').split('|').map((s) => s.trim()).filter(Boolean).concat(['hostinger']);
const text = '// Generated by scripts/make-evals-data.js from an eval run in rk-assistant. Do not edit by hand.\nwindow.EVALS = ' + JSON.stringify(out, null, 2) + ';\n';
for (const t of BLOCKED) if (text.toLowerCase().includes(t.toLowerCase())) { console.error('ABORT: blocked term found: ' + t); process.exit(1); }
fs.writeFileSync(path.join(__dirname, '..', 'site', 'evals', 'data.js'), text);
console.log('wrote site/evals/data.js', out.total, 'cases', out.attempts, 'attempts');
